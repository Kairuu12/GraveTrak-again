export function normalizeAppRole(role) {
  const safeRole = String(role || '').trim().toLowerCase().replace(/\s+/g, '-').replace(/_/g, '-');
  if (['staff', 'admin', 'cemetery-staff', 'cemetery-admin', 'cemetery-staff-user'].includes(safeRole)) return 'staff';
  if (['planning', 'planner', 'city-planner', 'city-planning'].includes(safeRole)) return 'planning';
  if (['mayor', 'mayors-office', 'mayor-office'].includes(safeRole)) return 'mayor';
  if (['user', 'public', 'registered-user'].includes(safeRole)) return 'user';
  return safeRole || 'user';
}

